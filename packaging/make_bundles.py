#!/usr/bin/env python3
"""
Build the release bundles that start the real arm without a developer setup.

windows: a zip with the launcher scripts, the host-side bridges, an embedded Python with
    pyserial, and a compose file that pulls the tested image by digest. Docker Desktop is the
    only thing the laptop needs.
macos: the source tree at the tag with a double-click installer, since the Mac app runs the
    workspace natively and cannot ship a prebuilt one.

The zips are reproducible: the same inputs give the same bytes. Set SOURCE_DATE_EPOCH to the
commit time. See docs/RELEASING.md.
"""

import argparse
import ast
import os
from pathlib import Path
import plistlib
import re
import stat
import string
import sys
import time
import zipfile

import yaml

ROOT = Path(__file__).resolve().parents[1]
VERSION_PATTERN = re.compile(r'^\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$')
IMAGE_PATTERN = re.compile(r'^ghcr\.io/[a-z0-9._/-]+@sha256:[0-9a-f]{64}$')
# The service the Windows launcher runs, and the bridges that run on the host beside it.
SERVICE = 'wslg-arm'
HOST_BRIDGES = ('carrier_relay', 'xinput_bridge')
# Outside the standard library, the host bridges may import only what the bundle carries.
HOST_THIRD_PARTY = {'serial'}
APP = 'packaging/macos/WayBionic Ground Station.app'


def zip_time():
    """Return the timestamp every file in a zip gets; zips cannot hold dates before 1980."""
    return time.gmtime(max(int(os.environ.get('SOURCE_DATE_EPOCH', '0')), 315532800))[:6]


class Bundle:
    """Collect files under one top folder and write them as a reproducible zip."""

    def __init__(self, top):
        self.top = top
        self.files = {}

    def add(self, name, data, executable=False):
        if isinstance(data, str):
            data = data.encode('utf-8')
        if name in self.files:
            raise ValueError(f'{name} is added twice')
        self.files[name] = (data, executable)

    def add_path(self, name, path):
        self.add(name, path.read_bytes(), bool(path.stat().st_mode & stat.S_IXUSR))

    def write(self, path):
        path.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as archive:
            for name in sorted(self.files):
                data, executable = self.files[name]
                info = zipfile.ZipInfo(f'{self.top}/{name}', zip_time())
                info.compress_type = zipfile.ZIP_DEFLATED
                info.create_system = 3
                info.external_attr = (stat.S_IFREG | (0o755 if executable else 0o644)) << 16
                archive.writestr(info, data)


def crlf(text):
    """Return text with Windows line endings, for files opened in Notepad or run by cmd."""
    return text.replace('\r\n', '\n').replace('\n', '\r\n')


def check_version(version):
    if not VERSION_PATTERN.match(version):
        raise ValueError(f'{version!r} is not a version like 1.2.3 or 1.2.3-rc1')


def release_compose(compose_text, image):
    """Return a compose file with the arm service alone, run from the pinned image."""
    if not IMAGE_PATTERN.match(image):
        raise ValueError(f'{image!r} is not an image pinned by digest')
    service = dict(yaml.safe_load(compose_text)['services'][SERVICE])
    # The bundle has no source to build from, and a lone service needs no profile.
    service.pop('build', None)
    service.pop('profiles', None)
    service['image'] = image
    for volume in service.get('volumes', []):
        source = volume.get('source', '') if isinstance(volume, dict) else str(volume)
        if source.startswith('.'):
            raise ValueError(f'{SERVICE} mounts {source}, which is not in the bundle')
    return ('# Generated by packaging/make_bundles.py from compose.yaml: the arm service, run\n'
            '# from the image the release was tested with, pinned by digest.\n'
            + yaml.safe_dump({'services': {SERVICE: service}}, sort_keys=False))


def host_modules(package_dir):
    """Return the waybionic_teleop modules the host bridges import, themselves included."""
    seen, queue = set(), list(HOST_BRIDGES)
    while queue:
        name = queue.pop()
        if name in seen:
            continue
        seen.add(name)
        tree = ast.parse((package_dir / f'{name}.py').read_text(encoding='utf-8'))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                modules, names = [alias.name.split('.') for alias in node.names], []
            elif isinstance(node, ast.ImportFrom):
                if node.level:
                    raise ValueError(f'{name} has a relative import; the bundle check needs '
                                     'absolute ones')
                modules, names = [node.module.split('.')], [alias.name for alias in node.names]
            else:
                continue
            for parts in modules:
                if parts[0] == 'waybionic_teleop':
                    queue.extend(parts[1:2] or names)
                elif parts[0] not in sys.stdlib_module_names | HOST_THIRD_PARTY:
                    raise ValueError(f'{name} imports {parts[0]}, which the Windows bundle '
                                     'does not carry')
    return sorted(seen)


def add_python(bundle, python_zip, site_packages):
    """Unpack the embeddable Python, point it at the bridges and add pyserial."""
    with zipfile.ZipFile(python_zip) as archive:
        for info in archive.infolist():
            if info.is_dir():
                continue
            data = archive.read(info)
            if info.filename.endswith('._pth'):
                # In this mode Python ignores PYTHONPATH and the working directory, so the
                # bridges' package and pyserial are named here, relative to this file.
                stem = info.filename[:-len('._pth')]
                data = f'{stem}.zip\r\n.\r\n..\\waybionic_teleop\r\nsite-packages\r\n'
            bundle.add(f'python/{info.filename}', data, info.filename.endswith('.exe'))
    for path in sorted(site_packages.rglob('*')):
        relative = path.relative_to(site_packages)
        if (path.is_file() and relative.parts[0] != 'bin'
                and '__pycache__' not in relative.parts):
            bundle.add('python/site-packages/' + relative.as_posix(), path.read_bytes())


def build_windows(args):
    check_version(args.version)
    package_dir = ROOT / 'waybionic_teleop' / 'waybionic_teleop'
    bundle = Bundle(f'WayBionic-Ground-Station-{args.version}')
    bundle.add_path('scripts/windows-arm.ps1', ROOT / 'scripts' / 'windows-arm.ps1')
    for name, path in (('scripts/windows-arm.cmd', ROOT / 'scripts' / 'windows-arm.cmd'),
                       ('Start WayBionic Arm.cmd',
                        ROOT / 'packaging' / 'windows' / 'Start WayBionic Arm.cmd'),
                       ('Check WayBionic Setup.cmd',
                        ROOT / 'packaging' / 'windows' / 'Check WayBionic Setup.cmd')):
        bundle.add(name, crlf(path.read_text(encoding='utf-8')))
    for module in host_modules(package_dir) + ['__init__']:
        bundle.add_path(f'waybionic_teleop/waybionic_teleop/{module}.py',
                        package_dir / f'{module}.py')
    bundle.add('compose.release.yaml',
               release_compose((ROOT / 'compose.yaml').read_text(encoding='utf-8'), args.image))
    bundle.add('VERSION', crlf(f'{args.version}\ncommit {args.commit}\nimage {args.image}\n'))
    readme = string.Template((ROOT / 'packaging' / 'windows' / 'README.txt').read_text(
        encoding='utf-8'))
    bundle.add('README.txt', crlf(readme.substitute(version=args.version, image=args.image)))
    add_python(bundle, args.python_zip, args.site_packages)
    path = args.out / f'waybionic-ground-station-windows-{args.version}.zip'
    bundle.write(path)
    return path


def build_macos(args):
    check_version(args.version)
    source = args.source
    bundle = Bundle(f'WayBionic-Ground-Station-{args.version}')
    for path in sorted(source.rglob('*')):
        relative = path.relative_to(source).as_posix()
        if path.is_symlink():
            raise ValueError(f'{relative} is a symlink, which the bundle does not hold')
        if path.is_file() and not relative.startswith('.git/'):
            bundle.add_path(relative, path)
    plist = f'{APP}/Contents/Info.plist'
    info = plistlib.loads(bundle.files[plist][0])
    info['CFBundleShortVersionString'] = info['CFBundleVersion'] = args.version
    bundle.files[plist] = (plistlib.dumps(info), False)
    bundle.add('Install WayBionic.command',
               (ROOT / 'packaging' / 'macos' / 'Install WayBionic.command').read_bytes(), True)
    bundle.add('README-macOS.txt',
               (ROOT / 'packaging' / 'macos' / 'README.txt').read_text(encoding='utf-8'))
    bundle.add('VERSION', f'{args.version}\ncommit {args.commit}\n')
    path = args.out / f'waybionic-ground-station-macos-{args.version}.zip'
    bundle.write(path)
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    commands = parser.add_subparsers(dest='command', required=True)
    for name in ('windows', 'macos'):
        command = commands.add_parser(name)
        command.add_argument('--version', required=True)
        command.add_argument('--commit', required=True)
        command.add_argument('--out', type=Path, required=True)
    windows, macos = commands.choices['windows'], commands.choices['macos']
    windows.add_argument('--image', required=True, help='repository@sha256:digest')
    windows.add_argument('--python-zip', type=Path, required=True)
    windows.add_argument('--site-packages', type=Path, required=True)
    macos.add_argument('--source', type=Path, required=True, help='the tag, from git archive')
    args = parser.parse_args(argv)
    print(build_windows(args) if args.command == 'windows' else build_macos(args))


if __name__ == '__main__':
    main()
